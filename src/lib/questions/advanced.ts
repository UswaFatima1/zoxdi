/**
 * Hand-authored advanced questions.
 *
 * These carry the "professional" end of the bank: the adjustments, the
 * treatment of bad debts, the vocabulary of capital vs revenue, and the
 * quality-of-judgement items that separate a bookkeeper from an accountant.
 * Every answer is a settled rule, so none of them are a matter of opinion.
 */

import type { ConceptId } from "@/lib/learning/concepts";
import type { BankOption, BankQuestion, Difficulty } from "./types";

const LETTERS = ["a", "b", "c", "d"] as const;

/** Build a question, placing the correct answer at a stable non-first slot. */
function make(
  id: string,
  topic: string,
  difficulty: Difficulty,
  prompt: string,
  correct: string,
  distractors: string[],
  explanation: string,
  conceptIds: ConceptId[],
): BankQuestion {
  const labels = [correct, ...distractors.filter((d) => d !== correct)].slice(0, 4);
  // Rotate the correct answer by a hash of the id so the answer is not always first.
  let hash = 0;
  for (let index = 0; index < id.length; index += 1) hash = (hash * 31 + id.charCodeAt(index)) >>> 0;
  const shift = hash % labels.length;
  const rotated = [...labels.slice(shift), ...labels.slice(0, shift)];
  const options: BankOption[] = rotated.map((label, index) => ({ id: LETTERS[index], label }));
  return {
    id,
    topic,
    difficulty,
    prompt,
    options,
    correctOptionId: LETTERS[rotated.indexOf(correct)],
    explanation,
    conceptIds,
  };
}

